//! 纪要提示词模板。
//!
//! **为什么在 cap-meeting 而不在 cap-llm**：cap-llm 的边界写明「不写提示词、
//! 不做业务编排」—— 协议与传输是基础设施，纪要长什么样是产品差异。
//! 把提示词塞进 cap-llm 会让所有调用它的产品被迫接受同一套纪要口径，
//! 那是把产品决策藏进基础设施。
//!
//! 下游若要换口径，用 [`PROMPT_TEMPLATE`] 自己拼一份，覆盖 [`SYSTEM_PROMPT`]。

/// 系统提示词。
///
/// 四条约束是本模板的核心，缺一不可：
/// 1. **只依据原文**，不补充、不演绎、不脑补未讨论的内容
/// 2. **缺信息就留空**，不许填「未知」「待定」占位
/// 3. **待办必须有可执行动词**，没有具体动作的条目不要列
/// 4. **JSON 是唯一输出**，不加围栏、不加解释
///
/// 第 2 条是本项目最看重的一条：占位符会一路走到产品界面上，
/// 用户看到「负责人：未知」比看到空白更糟 —— 它看起来像一个结论。
pub const SYSTEM_PROMPT: &str = r#"你是会议纪要整理助手。你的任务是把会议的原始文字内容整理成结构化纪要。

严格遵守以下规则：
1. 只依据原文整理，不补充、不演绎、不脑补未讨论的内容。
2. 原文没提到的信息一律留空（JSON 里用 null 或空数组），**绝对不要**填「未知」「待定」「N/A」等占位词。这些占位词会被下游当作真实数据展示。
3. 待办事项必须是可执行的具体动作，且原文里确实有人认领或明确指出。没有具体动作或没有负责人的，不要硬凑进 actions。
4. 决议必须是会上真正拍板的结论，讨论过但没定论的放进 open_questions。
5. 负责人、截止时间从原文里提取，没有就留 null。

输出格式：直接输出一个 JSON 对象，不要用 markdown 代码围栏包裹，不要有任何额外文字。

JSON 结构如下：
{
  "title": "会议主题（从原文推断，推不出用「会议纪要」）",
  "summary": "一句话概括本次会议",
  "topics": [
    {"title": "议题名", "summary": "该议题的讨论要点"}
  ],
  "decisions": [
    {"content": "决议内容", "rationale": "依据或背景，没有则为 null"}
  ],
  "actions": [
    {"task": "待办内容", "owner": "负责人，没有则为 null", "due": "截止时间原文，没有则为 null"}
  ],
  "open_questions": ["待定事项或风险"]
}"#;

/// 用户 prompt 模板。`{meta}` 是会议元信息（标题/时间/参会人），
/// `{text}` 是会议原文。空字符串时元信息段整体不出现。
pub const PROMPT_TEMPLATE: &str = r#"{meta}以下是会议原始文字内容：

{text}
"#;
